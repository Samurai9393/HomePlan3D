type Key = keyof typeof en | EditorKey;

export type I18nKey = Key;

const more: Record<string, string> = {};

/** Add editor-only English texts to the table when the editor bundle loads. */
export function addTexts(texts: Record<string, string>): void {
  Object.assign(more, texts);
}

export function translate(_hass: HomeAssistant | undefined, key: Key, vars: Record<string, string | number> = {}): string {
  const table = en as Record<string, string>;
  let s: string = table[key] ?? more[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function formatNumber(hass: HomeAssistant | undefined, value: number, digits = 2): string {
  return value.toLocaleString(hass?.language ?? undefined, { maximumFractionDigits: digits });
}
